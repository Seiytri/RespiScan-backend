import io
from datetime import date
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from diagnostics.models import Scan, Diagnosis
from patients.models import Patient


def generate_clinical_pdf(scan_id: int) -> bytes:
    """Generate a clinical report PDF for a single scan/diagnosis."""
    scan = Scan.objects.select_related('patient', 'diagnosis').get(id=scan_id)
    patient = scan.patient
    diagnosis = scan.diagnosis

    buffer = io.BytesIO()
    p = canvas.Canvas(buffer, pagesize=letter)

    p.setFont("Helvetica-Bold", 16)
    p.drawString(100, 750, "RespiScan Clinical Report")

    p.setFont("Helvetica", 12)

    name = patient.name if patient else "N/A"
    pid = patient.patient_id if patient else "N/A"
    age = patient.age if patient else "N/A"
    gender = patient.gender if patient else "N/A"

    p.drawString(100, 710, f"Patient Name: {name}")
    p.drawString(100, 690, f"Patient ID: {pid}")
    p.drawString(100, 670, f"Age: {age}")
    p.drawString(100, 650, f"Gender: {gender}")

    p.drawString(100, 610, f"Upload Date: {scan.created_at.strftime('%Y-%m-%d %H:%M')}")
    p.drawString(100, 590, f"Filename: {scan.original_filename}")

    det_result = diagnosis.detection_result if diagnosis else "N/A"
    conf = diagnosis.model_confidence if diagnosis else "N/A"
    notes = diagnosis.radiologist_notes if diagnosis else ""

    p.drawString(100, 550, f"Diagnosis Result: {det_result}")
    p.drawString(100, 530, f"Confidence: {conf}")

    if notes:
        p.drawString(100, 490, "Radiologist Notes:")
        p.drawString(100, 470, notes[:80])

    p.showPage()
    p.save()

    buffer.seek(0)
    return buffer.read()


def generate_analytics_pdf(start_date: date, end_date: date) -> bytes:
    """
    Generate an analytics summary PDF for a given date range.
    Aggregates patient, scan, and diagnosis stats.
    """
    buffer = io.BytesIO()
    p = canvas.Canvas(buffer, pagesize=letter)
    width, height = letter
    y = height - 60

    # Title
    p.setFont("Helvetica-Bold", 18)
    p.drawString(60, y, "RespiScan Analytics Report")
    y -= 30

    p.setFont("Helvetica", 11)
    p.drawString(60, y, f"Period: {start_date.strftime('%B %d, %Y')} — {end_date.strftime('%B %d, %Y')}")
    y -= 10

    # Divider line
    p.setStrokeColor(colors.grey)
    p.line(60, y, width - 60, y)
    y -= 30

    # Compute stats
    total_patients = Patient.objects.filter(is_active=True).count()
    new_patients = Patient.objects.filter(
        is_active=True,
        created_at__date__gte=start_date,
        created_at__date__lte=end_date,
    ).count()

    total_scans = Scan.objects.filter(
        created_at__date__gte=start_date,
        created_at__date__lte=end_date,
    ).count()

    positive = Diagnosis.objects.filter(
        detection_result='Positive',
        diagnosed_at__date__gte=start_date,
        diagnosed_at__date__lte=end_date,
    ).count()

    negative = Diagnosis.objects.filter(
        detection_result='Negative',
        diagnosed_at__date__gte=start_date,
        diagnosed_at__date__lte=end_date,
    ).count()

    pending = Diagnosis.objects.filter(
        detection_result='Pending',
        diagnosed_at__date__gte=start_date,
        diagnosed_at__date__lte=end_date,
    ).count()

    # Section: Summary Statistics
    p.setFont("Helvetica-Bold", 14)
    p.drawString(60, y, "Summary Statistics")
    y -= 25

    p.setFont("Helvetica", 12)
    stats = [
        ("Total Registered Patients", str(total_patients)),
        ("New Patients (This Period)", str(new_patients)),
        ("CXR Scans Processed", str(total_scans)),
        ("Positive Detections", str(positive)),
        ("Negative Results", str(negative)),
        ("Pending Diagnoses", str(pending)),
    ]

    for label, value in stats:
        p.drawString(80, y, f"{label}:")
        p.drawString(320, y, value)
        y -= 20

    y -= 20

    # Section: Detection Rate
    p.setFont("Helvetica-Bold", 14)
    p.drawString(60, y, "Detection Rate")
    y -= 25

    p.setFont("Helvetica", 12)
    total_diagnosed = positive + negative
    if total_diagnosed > 0:
        rate = (positive / total_diagnosed) * 100
        p.drawString(80, y, f"Positive Rate: {rate:.1f}%")
        y -= 20
        p.drawString(80, y, f"Out of {total_diagnosed} completed diagnoses")
    else:
        p.drawString(80, y, "No completed diagnoses in this period.")
    y -= 40

    # Footer
    p.setFont("Helvetica-Oblique", 9)
    p.setFillColor(colors.grey)
    p.drawString(60, 40, f"Generated by RespiScan — {date.today().strftime('%Y-%m-%d')}")
    p.drawString(60, 28, "This report is auto-generated and for internal use only.")

    p.showPage()
    p.save()

    buffer.seek(0)
    return buffer.read()
